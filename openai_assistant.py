"""
Модуль для генерации персонализированных рекомендаций через OpenAI API
"""
import os
import logging
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv()

# Инициализация клиента OpenAI
client = OpenAI(api_key=os.getenv('OPENAI_API_KEY'))

# Системный промпт из ChatGPT-Prompt.md
SYSTEM_PROMPT = """Ты — Роман Дусенко, психолог, стратег и навигатор личных стратегий для предпринимателей. Твой тон — спокойный, глубокий, уважительный ("на ты", но с дистанцией взрослого разговора). Ты избегаешь дешевой мотивации ("ты сможешь!", "вперед к целям!"). Твой фокус — честность, тишина, взрослость.

Твоя задача: Написать персональное заключение для "Бортового журнала" участника на основе его ответов. Это должен быть не просто отчет, а "Лоция" — карта его текущего состояния.

**Структура ответа (строго 4 блока):**

## **1. Диагноз Навигатора**

Сравни внешнюю роль и внутреннее ощущение.

* Если они конфликтуют (например, "Лидер" vs "Уставший"), напиши о цене этого разрыва. Используй метафору: "Твой корабль выглядит как [внешняя роль], но в машинном отделении [внутреннее ощущение]".
* Если они совпадают, подтверди целостность курса.

## **2. Штормовое предупреждение**

Посмотри на статус навигации и цену откладывания.

* Если статус "Переход/Шторм", объясни, что старая карта больше не работает, и это нормально.
* Укажи на цену. Скажи жестко, но бережно: "Ты платишь валютой '[цена]'. Это слишком дорогой тариф для долгого плавания".

## **3. Точка тишины**

Дай рекомендацию, как использовать слово-якорь.

* Свяжи это с семьей. Если он написал, что с семьей он "в телефоне", предложи практику: "Когда приходишь домой, бросай якорь '[слово]' в прихожей, чтобы быть с ними".

## **4. Ориентир**

Посмотри на его главный вопрос.

* Не давай готовый ответ. Дай метафору или встречный вопрос, который поможет ему найти ответ самому. Заверши фразой в духе: "Берег рядом. Курс проложен".

**Важно:** Объем до 300 слов. Пиши связным текстом, красиво, литературно."""


def generate_personal_strategy(user_data: dict) -> str:
    """
    Генерирует персонализированное заключение на основе данных пользователя

    Args:
        user_data: Словарь с данными пользователя

    Returns:
        Текст персонализированного заключения
    """
    try:
        # Формируем пользовательский промпт с данными
        user_prompt = f"""**Входные данные Капитана:**

1. Имя: {user_data.get('full_name', 'Неизвестный')}
2. Внешняя Роль (как видят): {user_data.get('role_outer', '-')}
3. Внутреннее ощущение: {user_data.get('role_inner', '-')}
4. Состояние навигации (тест): {user_data.get('nav_score', '-')}
5. Где мысли с семьей: {user_data.get('family_presence', '-')}
6. Слово-якорь: {user_data.get('anchor_word', '-')}
7. Цена откладывания: {user_data.get('cost_of_delay', '-')}
8. Главный вопрос: {user_data.get('final_question', '-')}

Напиши персональное заключение по структуре из системного промпта."""

        # Вызываем OpenAI API
        response = client.chat.completions.create(
            model="gpt-4o-mini",  # Используем более быструю и дешевую модель
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ],
            temperature=0.8,  # Немного креативности
            max_tokens=800  # Примерно 300 слов на русском
        )

        strategy_text = response.choices[0].message.content.strip()
        logging.info(f"Generated personal strategy for user {user_data.get('full_name', 'Unknown')}")
        return strategy_text

    except Exception as e:
        logging.error(f"OpenAI API Error: {e}")
        # Возвращаем запасной текст в случае ошибки
        return """## Навигация продолжается

Твой бортовой журнал зафиксировал важные координаты. Это начало маршрута, а не конец пути.

Разрыв между внешней ролью и внутренним состоянием — это не слабость. Это сигнал о том, что старая карта требует обновления.

Обрати внимание на цену, которую ты платишь за откладывание решений. Каждый день промедления — это не время ожидания, а реальная валюта твоей жизни.

Твой главный вопрос — это не проблема, требующая решения. Это компас, указывающий направление. Следуй за ним.

Берег рядом. Курс проложен."""


def validate_answer(question: str, answer: str, context: str = "") -> dict:
    """
    Проверяет адекватность и качество ответа пользователя через OpenAI API

    Args:
        question: Вопрос, на который пользователь отвечает
        answer: Ответ пользователя
        context: Дополнительный контекст (необязательно)

    Returns:
        Словарь с результатами валидации:
        {
            'is_valid': bool,  # True если ответ адекватен
            'feedback': str,   # Обратная связь/подсказка для пользователя (если нужна)
            'suggestion': str  # Предложение как улучшить ответ (опционально)
        }
    """
    try:
        # Системный промпт для валидации
        validation_prompt = """Ты — снисходительный валидатор ответов для психологического опроса предпринимателей.
Твоя задача: отклонять только ЯВНО неадекватные ответы (троллинг, бессмыслица, оскорбления).

Критерии ВАЛИДНОГО ответа:
1. Любое осмысленное слово или фраза на русском языке
2. Для вопросов "одним словом" - принимай даже очень короткие ответы (1 слово)
3. Для открытых вопросов - принимай любые ответы от 2-3 слов
4. Если это похоже на вопрос (есть "как", "что", "когда", "?") - ВСЕГДА принимай
5. Даже простые ответы типа "не знаю", "устал", "работа" - ПРИНИМАЙ, если они искренние

Критерии НЕВАЛИДНОГО ответа (отклоняй ТОЛЬКО это):
- Явная бессмыслица (набор случайных букв/символов: "asdfgh", ";;;")
- Троллинг или неуважительные ответы
- Пустая строка или только пробелы
- Оскорбления

ВАЖНО:
- Будь МАКСИМАЛЬНО снисходительным
- В случае сомнений - ПРИНИМАЙ ответ
- Короткие вопросы "как...?", "что...?" - ВСЕГДА валидны
- Не требуй развернутых ответов - люди отвечают по-разному

Ответь в формате JSON:
{
  "is_valid": true/false,
  "feedback": "Короткая обратная связь (только если ответ ЯВНО невалидный)",
  "suggestion": ""
}"""

        user_message = f"""Вопрос: {question}
Ответ пользователя: {answer}
{f"Контекст: {context}" if context else ""}

Оцени ответ по критериям."""

        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": validation_prompt},
                {"role": "user", "content": user_message}
            ],
            temperature=0.3,  # Меньше креативности, больше строгости
            max_tokens=200,
            response_format={"type": "json_object"}  # Запрашиваем JSON
        )

        result = response.choices[0].message.content.strip()

        # Парсим JSON
        import json
        validation_result = json.loads(result)

        logging.info(f"Answer validation: {validation_result.get('is_valid', False)}")
        return validation_result

    except Exception as e:
        logging.error(f"Answer validation error: {e}")
        # В случае ошибки API — пропускаем валидацию (считаем ответ валидным)
        return {
            'is_valid': True,
            'feedback': '',
            'suggestion': ''
        }


def test_openai_connection() -> bool:
    """
    Проверяет подключение к OpenAI API

    Returns:
        True если подключение успешно, False в противном случае
    """
    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": "Тест"}],
            max_tokens=10
        )
        logging.info("OpenAI API connection successful")
        return True
    except Exception as e:
        logging.error(f"OpenAI API connection failed: {e}")
        return False


